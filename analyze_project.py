ROOT=Path(__file__).resolve().parent
for x in ['data','figures']: (ROOT/x).mkdir(exist_ok=True)
G0=9.80665; RE=6371000.; RU=8314.462618
PC=1e6; PTANK=1.8e6; OF=3.2; EPS=3.; ETA=0.95
PAYLOAD=70.; CAPSULE=0.; DELIVERY=PAYLOAD+CAPSULE
DIA=.45; AREF=np.pi*DIA**2/4; DRY_FRACTION=.35; FIXED_PER_STAGE=90.; TWR=1.8
# State correspondence uses real-fluid differences only; Cantera anchors formation enthalpy.
def reactant_h(spec,fluid,T,P=PTANK):
 g=ct.Solution('gri30.yaml');g.TPX=298.15,101325,{spec:1}
 return g.enthalpy_mass+PropsSI('H','T',T,'P',P,fluid)-PropsSI('H','T',298.15,'P',101325,fluid)
def combustion(of=OF,pc=PC,fuel='CH4',fluid='Methane',Tf=111.7):
 hf=reactant_h(fuel,fluid,Tf,13e6);ho=reactant_h('O2','Oxygen',90.2)
 hin_cold=(hf+of*ho)/(1+of); heat_recovery=400000.; hin=hin_cold+heat_recovery
 g=ct.Solution('gri30.yaml');g.TPY=298.15,pc,{fuel:1,'O2':of}
 # Establish a product composition with the same elements so the cold-liquid
 # target enthalpy is representable before the final equilibrium calculation.
 g.equilibrate('HP');g.HP=hin,pc;g.equilibrate('HP',rtol=1e-10)
 return g,dict(Tc=g.T,MW=g.mean_molecular_weight,R=ct.gas_constant/g.mean_molecular_weight,cp=g.cp_mass,gamma=g.cp_mass/g.cv_mass,mu=g.viscosity,k=g.thermal_conductivity,Pr=g.cp_mass*g.viscosity/g.thermal_conductivity,hin=hin,hin_cold=hin_cold,heat_recovery=heat_recovery,hout=g.enthalpy_mass,hf=hf,ho=ho,Y=dict(zip(g.species_names,g.Y)),X={n:float(x) for n,x in zip(g.species_names,g.X) if x>1e-5},energy_residual=g.enthalpy_mass-hin)
def area_m(M,ga): return ((2/(ga+1)*(1+(ga-1)/2*M*M))**((ga+1)/(2*(ga-1))))/M
def nozzle(thermo,pc=PC,eps=EPS):
 ga=thermo['gamma'];R=thermo['R'];Tc=thermo['Tc']
 Me=brentq(lambda m:area_m(m,ga)-eps,1.0000001,15)
 Te=Tc/(1+(ga-1)/2*Me**2);Pe=pc*(Te/Tc)**(ga/(ga-1));Ve=Me*np.sqrt(ga*R*Te)
 cs=np.sqrt(R*Tc/ga)*((ga+1)/2)**((ga+1)/(2*(ga-1)))
 cevac=Ve+Pe*eps*cs/pc;cesl=cevac-101325*eps*cs/pc
 return dict(Me=Me,Te=Te,Pe=Pe,Ve=Ve,cstar=cs,CFvac=cevac/cs,CFsl=cesl/cs,Ispvac=cevac/G0,Ispsl=cesl/G0,cevac=cevac,cesl=cesl)
GAS,THERMO=combustion();NZ=nozzle(THERMO)
# US Standard Atmosphere 1976 lower layers: geopotential altitude through 84.852 km.
HB=np.array([0,11000,20000,32000,47000,51000,71000,84852.]);LR=np.array([-.0065,0,.001,.0028,0,-.0028,-.002]);TB=[288.15];PB=[101325.]
for i,L in enumerate(LR):
 dh=HB[i+1]-HB[i];T=TB[-1]+L*dh
 P=PB[-1]*(T/TB[-1])**(-G0/(287.05287*L)) if L else PB[-1]*np.exp(-G0*dh/(287.05287*TB[-1]))
 TB.append(T);PB.append(P)
def atmosphere(h):
 h=max(h,0.);H=RE*h/(RE+h)
 if H>=HB[-1]:
  # Explicit negligible-density exponential extension, not a full upper-atmosphere model.
  T=TB[-1];P=PB[-1]*np.exp(-(H-HB[-1])*G0/(287.05287*T))
 else:
  i=min(np.searchsorted(HB,H,side='right')-1,len(LR)-1);L=LR[i];T=TB[i]+L*(H-HB[i])
  P=PB[i]*(T/TB[i])**(-G0/(287.05287*L)) if L else PB[i]*np.exp(-G0*(H-HB[i])/(287.05287*T))
 return P/(287.05287*T),P,np.sqrt(1.4*287.05287*T)
def cd(M,coast=False):
 # Declared preliminary transonic envelope; not fitted vehicle-specific data.
 return np.interp(M,[0,.5,.8,1.05,1.2,2,3,5,10],[.35,.35,.42,.75,.70,.48,.38,.32,.30])+(0.10 if coast else 0)
def build_stages(n,dv,delivery=DELIVERY,eps_struct=DRY_FRACTION):
 # Equal ideal delta-V preliminary allocation, common effective vacuum velocity.
 c=ETA*NZ['cevac'];r=np.exp(dv/n/c);e=eps_struct;k=e/(1-e);L=delivery;st=[]
 for i in range(n-1,-1,-1):
  prop=(r-1)*(L+FIXED_PER_STAGE)/(1-k*(r-1));dry=k*prop+FIXED_PER_STAGE
  if prop<=0: raise ValueError('Infeasible mass ratio')
  m0=L+dry+prop;targetF=TWR*m0*G0
  cign=ETA*(NZ['cesl'] if i==0 else NZ['cevac'])
  mdot=targetF/cign;At=mdot*NZ['cstar']/PC
  st.append(dict(stage=i+1,prop=prop,dry=dry,carried=L,m0=m0,mf=L+dry,mdot=mdot,At=At,Ae=EPS*At,tb=prop/mdot))
  L=m0
 return list(reversed(st))
def fly(stages,drag_scale=1.,perf_scale=1.,delivery_extra=0.,maxstep=.25):
 # Integrate [h,v,m,integral F/m,integral g,integral D/m].
 y=np.array([0.,0.,stages[0]['m0']+delivery_extra,0.,0.,0.]);t0=0.;hist=[];events=[]
 for j,s in enumerate(stages):
  def rhs(t,y):
   h,v,m=y[:3];rho,pa,a=atmosphere(h);D=.5*rho*v*abs(v)*AREF*cd(abs(v)/a)*drag_scale
   F=ETA*perf_scale*(s['mdot']*NZ['Ve']+(NZ['Pe']-pa)*s['Ae']);g=G0*(RE/(RE+h))**2
   return [v,F/m-g-D/m,-s['mdot'],F/m,g,D/m]
  sol=solve_ivp(rhs,[t0,t0+s['tb']],y,rtol=2e-9,atol=1e-8,max_step=maxstep,dense_output=True)
  ts=np.linspace(t0,sol.t[-1],max(101,int(s['tb']*10)))
  for tt,yy in zip(ts,sol.sol(ts).T):
   h,v,m=yy[:3];rho,pa,a=atmosphere(h);D=.5*rho*v*abs(v)*AREF*cd(abs(v)/a)*drag_scale;F=ETA*perf_scale*(s['mdot']*NZ['Ve']+(NZ['Pe']-pa)*s['Ae']);g=G0*(RE/(RE+h))**2
   hist.append([tt,*yy,F,D,F/m-g-D/m,(F-D)/m/G0,.5*rho*v*v,j+1])
  y=sol.y[:,-1];t0=sol.t[-1];events.append(dict(event=f'Stage {j+1} burnout',t=t0,h=y[0],v=y[1],m=y[2]))
  if j<len(stages)-1:
   y[2]-=s['dry'];events.append(dict(event=f'Stage {j+1} separation / stage {j+2} ignition',t=t0,h=y[0],v=y[1],m=y[2]))
 def coast(t,y):
  h,v,m=y[:3];rho,pa,a=atmosphere(h);D=.5*rho*v*abs(v)*AREF*cd(abs(v)/a,True)*drag_scale;g=G0*(RE/(RE+h))**2
  return [v,-g-D/m,0,0,g,D/m]
 def apogee(t,y):return y[1]
 apogee.terminal=True;apogee.direction=-1
 sol=solve_ivp(coast,[t0,t0+1000],y,events=apogee,rtol=2e-9,atol=1e-8,max_step=maxstep,dense_output=True)
 ts=np.linspace(t0,sol.t[-1],500)
 for tt,yy in zip(ts,sol.sol(ts).T):
  h,v,m=yy[:3];rho,pa,a=atmosphere(h);D=.5*rho*v*abs(v)*AREF*cd(abs(v)/a,True)*drag_scale;g=G0*(RE/(RE+h))**2
  hist.append([tt,*yy,0,D,-g-D/m,-D/m/G0,.5*rho*v*v,0])
 events.append(dict(event='Apogee',t=sol.t[-1],h=sol.y[0,-1],v=sol.y[1,-1],m=sol.y[2,-1]))
 return np.array(hist),events
HEADER=['t_s','altitude_m','velocity_m_s','mass_kg','propulsive_dv_m_s','gravity_integral_m_s','drag_integral_m_s','thrust_N','drag_N','inertial_accel_m_s2','proper_load_g','dynamic_pressure_Pa','stage']
def solve_trade(n,target=155000.):
 def obj(dv):return fly(build_stages(n,dv),maxstep=1.)[1][-1]['h']-target
 upper=min(3500, .98*n*ETA*NZ['cevac']*np.log(1/DRY_FRACTION));dv=brentq(obj,1500,upper,xtol=1e-5);st=build_stages(n,dv);a,e=fly(st)
 return dict(n=n,dv_vac=dv,stages=st,m0=st[0]['m0'],prop=sum(s['prop'] for s in st),dry=sum(s['dry'] for s in st),events=e,peak_load=float(max(a[:,10])),max_q=float(max(a[:,11])),apogee=e[-1]['h']),a
if __name__=='__main__':
 trade=[]
 for n in [1,2,3]:
  tr,a=solve_trade(n);trade.append(tr);np.savetxt(ROOT/f'data/trajectory_{n}stage.csv',a,delimiter=',',header=','.join(HEADER),comments='')
 print('THERMO',json.dumps({k:v for k,v in THERMO.items() if k not in ['X','Y']},indent=2));print('NOZZLE',NZ)
 for tr in trade:print('TRADE',json.dumps(tr,indent=2))
 out=dict(thermo=THERMO,nozzle=NZ,trade=trade,settings=dict(PC=PC,PTANK=PTANK,OF=OF,EPS=EPS,ETA=ETA,PAYLOAD=PAYLOAD,CAPSULE=CAPSULE,DIA=DIA,DRY_FRACTION=DRY_FRACTION,FIXED_PER_STAGE=FIXED_PER_STAGE,TWR=TWR))
 (ROOT/'data/analysis.json').write_text(json.dumps(out,indent=2))
